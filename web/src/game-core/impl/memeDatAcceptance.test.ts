import { readFile } from "node:fs/promises";
import { describe, expect, it } from "vitest";
import {
  extractGroupedDatLevels,
  parseDatFile,
} from "@content/api/series-file";
import {
  replaySolutionCodec,
  type ReplayRecordedMove,
} from "@game-core/api/codec";
import type { EngineState } from "@game-core/api/model";
import { MS_DIRECTION, MS_TILE } from "@ruleset-ms/api/tiles";
import { msRegisteredLevelLoadRegistration } from "@ruleset-ms/impl/builtinLevelRegistration";
import {
  advanceMsInteractiveSession,
  createMsInteractiveSession,
  createMsReplaySession,
} from "@ruleset-ms/impl/engine";
import { lynxRegisteredLevelLoadRegistration } from "@ruleset-lynx/impl/builtinLevelRegistration";
import {
  advanceLynxInteractiveSession,
  createLynxInteractiveSession,
  createLynxReplaySession,
} from "@ruleset-lynx/impl/engine";
import {
  captureMsUndoCheckpoint,
  restoreMsUndoCheckpoint,
} from "@undo-runtime/impl/msCheckpoint";
import {
  captureLynxUndoCheckpoint,
  restoreLynxUndoCheckpoint,
} from "@undo-runtime/impl/lynxCheckpoint";

type Source = ReturnType<typeof extractGroupedDatLevels>["levels"][number];

function encodedReplay(moves: ReplayRecordedMove[]) {
  const bytes = replaySolutionCodec.encode(1, "MEME", 1000, {
    flags: 0,
    randomSlideDirection: MS_DIRECTION.north,
    stepping: 0,
    randomSeed: 123456789,
    moves: moves.map(({ when, dir }) => ({ when, dir })),
  });
  const decoded = replaySolutionCodec.decode(bytes);
  if (!decoded) throw new Error("Expected encoded acceptance replay");
  return decoded;
}

function createMsDriver(source: Source) {
  const request = {
    seriesFile: "MEME_ACCEPTANCE.dat",
    levelNumber: 1,
    ruleset: "MS" as const,
  };
  const level = msRegisteredLevelLoadRegistration.prepareLoadedLevel(source);
  let session = createMsInteractiveSession(request, level);
  return {
    state: () => session.state.engine,
    tanks: () =>
      session.state.internal.creatures
        .filter(
          (actor) => actor.id === MS_TILE.RedTank || actor.id === MS_TILE.Tank,
        )
        .map(({ id, pos, dir }) => ({ id, pos, dir })),
    advance(input: number) {
      session = advanceMsInteractiveSession(session, input);
    },
    checkpoint() {
      const checkpoint = captureMsUndoCheckpoint(session);
      return () => {
        session = restoreMsUndoCheckpoint(checkpoint);
      };
    },
    replay() {
      session = createMsReplaySession(
        request,
        level,
        encodedReplay(session.recordedMoves),
      );
    },
  };
}

function createLynxDriver(source: Source) {
  const request = {
    seriesFile: "MEME_ACCEPTANCE.dat",
    levelNumber: 1,
    ruleset: "Lynx" as const,
  };
  const level = lynxRegisteredLevelLoadRegistration.prepareLoadedLevel(source);
  let session = createLynxInteractiveSession(request, level);
  return {
    state: () => session.state,
    tanks: () =>
      session.actors
        .filter(
          (actor) =>
            !actor.hidden &&
            (actor.id === MS_TILE.RedTank || actor.id === MS_TILE.Tank),
        )
        .map(({ id, pos, dir }) => ({ id, pos, dir })),
    advance(input: number) {
      session = advanceLynxInteractiveSession(session, input);
    },
    checkpoint() {
      const checkpoint = captureLynxUndoCheckpoint(session);
      return () => {
        session = restoreLynxUndoCheckpoint(checkpoint);
      };
    },
    replay() {
      session = createLynxReplaySession(
        request,
        level,
        encodedReplay(session.recordedMoves),
      );
    },
  };
}

function progress(driver: {
  state(): EngineState;
  tanks(): Array<{ id: number; pos: number; dir: number }>;
}) {
  const state = driver.state();
  return structuredClone({
    hintTrail: state.hintTrail,
    boots: state.inventory.boots,
    tanks: driver.tanks(),
  });
}

describe("DATTools authored Meme DAT acceptance", () => {
  it.each(["MS", "Lynx"] as const)(
    "loads and plays the exported DAT with %s, undo and encoded replay",
    async (ruleset) => {
      // Byte-identical to DATTools/fixtures/dat/MEME_ACCEPTANCE.dat, generated by its
      // scripts/memeAcceptanceFixture.ts using real editor placement and encodeDatBytes.
      const bytes = new Uint8Array(
        await readFile(
          new URL(
            "../../../../fixtures/meme-tiles/MEME_ACCEPTANCE.dat",
            import.meta.url,
          ),
        ),
      );
      const parsed = parseDatFile(bytes, { ruleset });
      expect(parsed.levelCount).toBe(1);
      expect(parsed.levels[0]).toMatchObject({
        name: "Meme tiles acceptance",
        author: "DATTools",
        password: "MEME",
        timeLimitSeconds: 200,
        chipsRequired: 0,
        hasSpecialTools: false,
      });
      const source = extractGroupedDatLevels(bytes).levels[0]!;
      const registration =
        ruleset === "MS"
          ? msRegisteredLevelLoadRegistration
          : lynxRegisteredLevelLoadRegistration;
      const decoded = registration.decodeLoadedLevel(source);
      expect(decoded.badTiles).toBe(false);
      expect(decoded.hintText).toBe("A B");
      expect(decoded.creaturePositions).toEqual([330, 334, 458, 462, 338]);
      expect(
        [330, 334, 458, 462].map((index) => decoded.cells[index]!.top.id),
      ).toEqual([0x7c, 0x7d, 0x7e, 0x7f]);
      expect(
        [330, 334, 458, 462].map((index) => decoded.cells[index]!.bottom.id),
      ).toEqual([
        MS_TILE.Gravel,
        MS_TILE.Gravel,
        MS_TILE.Gravel,
        MS_TILE.Gravel,
      ]);
      const driver =
        ruleset === "MS" ? createMsDriver(source) : createLynxDriver(source);
      const stepEast = () => {
        driver.advance(MS_DIRECTION.east);
        for (let tick = 1; tick < 5; tick++) driver.advance(MS_DIRECTION.none);
      };
      const redDirections = () =>
        driver
          .tanks()
          .filter((actor) => actor.id === MS_TILE.RedTank)
          .map((actor) => actor.dir);
      stepEast();
      expect(driver.state().inventory.boots[4]).toBe(1);
      expect(driver.state().hintTrail?.marks).toEqual([
        { pos: 34, z: 1, text: "A" },
      ]);
      const restoreAfterPickup = driver.checkpoint();
      stepEast();
      expect(redDirections()).toEqual([
        MS_DIRECTION.east,
        MS_DIRECTION.north,
        MS_DIRECTION.west,
        MS_DIRECTION.south,
      ]);
      expect(
        driver.tanks().find((actor) => actor.id === MS_TILE.Tank)?.dir,
      ).toBe(MS_DIRECTION.east);
      stepEast();
      expect(redDirections()).toEqual([
        MS_DIRECTION.north,
        MS_DIRECTION.west,
        MS_DIRECTION.south,
        MS_DIRECTION.east,
      ]);
      stepEast();
      expect(driver.state().hintTrail).toEqual({
        nextIndex: 1,
        marks: [
          { pos: 34, z: 1, text: "A" },
          { pos: 35, z: 1, text: " " },
          { pos: 36, z: 1, text: "B" },
          { pos: 37, z: 1, text: "A" },
        ],
      });
      const completed = progress(driver);
      restoreAfterPickup();
      expect(driver.state().hintTrail?.marks).toEqual([
        { pos: 34, z: 1, text: "A" },
      ]);
      for (let step = 0; step < 3; step++) stepEast();
      expect(progress(driver)).toEqual(completed);
      driver.replay();
      for (let tick = 0; tick < 20; tick++) driver.advance(MS_DIRECTION.none);
      expect(progress(driver)).toEqual(completed);
    },
  );
});
