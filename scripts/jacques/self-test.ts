import assert from 'node:assert/strict';
import { MS_TILE } from '../../web/src/ruleset-ms/api/tiles';
import { loadLevel, createRun, tick, snapshot, buildWinningReplay, renderSvg, verifyDatBytes } from './harness';
assert.throws(() => verifyDatBytes(new Uint8Array([1, 2, 3])), /SHA-256/);
const loaded = await loadLevel(186);
assert.equal(loaded.metadata.number, 186);
assert.equal(loaded.level.cells.length, 1024);
const run = createRun(loaded);
assert.throws(() => buildWinningReplay(run), /completed/);
assert.equal(run.session.state.engine.replay.cursor, -1, 'manual run must record inputs');
const initial = snapshot(run);
tick(run, 0);
assert.equal(snapshot(run).currentTime, initial.currentTime + 1);
tick(run, 'E', 4);
assert.ok(run.session.recordedMoves.length > 0, 'accepted manual inputs must be recorded');
const svg = await renderSvg(run);
assert.match(svg, /data:image\/png;base64/);
assert.match(svg, /viewBox="0 0 1064 1084"/);
console.log('Jacques harness invariants passed');

const synthetic = structuredClone(loaded);
synthetic.level.cells = synthetic.level.cells.map((cell, pos) => ({ ...cell, top: { id: pos === 0 ? MS_TILE.Chip : pos === 1 ? MS_TILE.Exit : MS_TILE.Wall, state: 0 }, bottom: { id: MS_TILE.Empty, state: 0 } }));
synthetic.level.chipsNeeded = 0;
synthetic.level.creaturePositions = [];
synthetic.level.traps = [];
synthetic.level.cloners = [];
synthetic.level.layers = undefined;
const winning = createRun(synthetic);
tick(winning, 'E', 20);
assert.equal(snapshot(winning).status, 'completed');
assert.equal(buildWinningReplay(winning).trace.result.status, 'completed');
console.log('Synthetic terminal win round-trips through encoded TWS replay');
